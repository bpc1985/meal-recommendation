import type { MealType, Region } from '@mam/domain'
import type { dishes } from '../schema'

export type DishSeed = Omit<typeof dishes.$inferInsert, 'id' | 'createdAt' | 'isSeed'>

type MealCode = 'b' | 'l' | 'd'

const MEAL_BY_CODE: Record<MealCode, MealType> = {
  b: 'breakfast',
  l: 'lunch',
  d: 'dinner',
}

function meals(codes: string): MealType[] {
  return codes
    .split(' ')
    .filter(Boolean)
    .map((code) => MEAL_BY_CODE[code as MealCode])
}

/** Giá hiển thị nằm giữa khung ±15% — khung giá là ước lượng theo mặt bằng 2026. */
function priceRange(priceVnd: number): { priceMinVnd: number; priceMaxVnd: number } {
  const round = (value: number) => Math.round(value / 1_000) * 1_000
  return { priceMinVnd: round(priceVnd * 0.85), priceMaxVnd: round(priceVnd * 1.15) }
}

interface DishInput {
  slug: string
  nameVi: string
  nameEn: string
  priceVnd: number
  mealCodes: string
  tags: string
  region: Region
  prepMinutes: number
  fillLevel: 1 | 2 | 3
  descVi: string
  descEn: string
}

function dish(input: DishInput): DishSeed {
  return {
    slug: input.slug,
    nameVi: input.nameVi,
    nameEn: input.nameEn,
    priceVnd: input.priceVnd,
    ...priceRange(input.priceVnd),
    mealTypes: meals(input.mealCodes),
    tags: input.tags.split(' ').filter(Boolean),
    region: input.region,
    prepMinutes: input.prepMinutes,
    fillLevel: input.fillLevel,
    descVi: input.descVi,
    descEn: input.descEn,
  }
}

